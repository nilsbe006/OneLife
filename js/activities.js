export function costLabel(a) {
  const { min, max } = a.cost;
  if (max === 0) return 'Kostenlos';
  if (min === max) return `ca. ${min} €`;
  return `ca. ${min}–${max} €`;
}

export function driveLabel(a) {
  if (a.travel === 'flight') return 'Flugreise';
  if (a.travel === 'train') return 'Mit dem Zug';
  return `~${a.driveMin} min ab Ulm`;
}

